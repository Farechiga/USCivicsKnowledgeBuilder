#!/usr/bin/env node
/* Build app/data.js from the question + term data.

   The app (app/index.html) reads two globals — TERMS and Q — that this
   script emits as a plain <script>-includable file. Regenerate whenever
   data/questions/*.json or data/terms.json change:

     node scripts/build-app-data.js

   Q is emitted in id order; the app shuffles it at runtime.                 */

const fs = require('fs');
const path = require('path');

const ROOT  = path.resolve(__dirname, '..');
const QDIR  = path.join(ROOT, 'data', 'questions');
const TERMS = path.join(ROOT, 'data', 'terms.json');
const OUT   = path.join(ROOT, 'app', 'data.js');

/* registrable-ish domain for the "Source:" line, e.g. blogs.loc.gov -> loc.gov */
const srcOf = url => {
  if (!url) return '';
  try {
    let h = new URL(url).hostname.replace(/^www\./, '');
    const p = h.split('.');
    return p.length > 2 ? p.slice(-2).join('.') : h;
  } catch { return ''; }
};

const termsRaw = JSON.parse(fs.readFileSync(TERMS, 'utf8')).terms;
const TERM_KEYS = new Set(Object.keys(termsRaw));

const TERMS_OUT = {};
for (const [k, e] of Object.entries(termsRaw)) {
  TERMS_OUT[k] = {
    term: e.term,
    pron: e.pronunciation,
    hard: !!e.hard_to_pronounce,
    kid:  e.kid_definition,
    ...(e.origin ? { origin: e.origin } : {})
  };
}

const qFiles = fs.readdirSync(QDIR)
  .filter(f => /^q\d+\.json$/.test(f))
  .sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));

const Q_OUT = qFiles.map(f => {
  const d = JSON.parse(fs.readFileSync(path.join(QDIR, f), 'utf8'));
  return {
    id:    d.id,
    q:     d.question_text,
    lead:  d.lead_in || null,
    dis:   d.disambiguation || null,
    ans:   (d.official_answers || []).map(a => a.text),
    why:   d.why_it_matters ? d.why_it_matters.text : '',
    fun:   d.fun_fact ? d.fun_fact.text : '',
    src:   srcOf(d.fun_fact && d.fun_fact.source_url),
    // only keep terms we actually have definitions for (drives the Vocabulary chips)
    terms: (d.term_ids || []).filter(t => TERM_KEYS.has(t)),
    mnem:  d.mnemonic ? { hook: d.mnemonic.hook, link: d.mnemonic.link_sentence } : null
  };
});

const banner =
`/* AUTO-GENERATED by scripts/build-app-data.js — do not edit by hand.
   Source: data/questions/*.json + data/terms.json
   Questions: ${Q_OUT.length} */\n`;

const body =
  banner +
  'const TERMS = ' + JSON.stringify(TERMS_OUT, null, 2) + ';\n\n' +
  'const Q = ' + JSON.stringify(Q_OUT, null, 2) + ';\n';

fs.writeFileSync(OUT, body);
console.log(`Wrote ${path.relative(ROOT, OUT)} — ${Q_OUT.length} questions, ${Object.keys(TERMS_OUT).length} terms`);
